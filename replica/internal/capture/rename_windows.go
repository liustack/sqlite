//go:build windows

package capture

import (
	"os"

	"golang.org/x/sys/windows"
)

// rename moves a staged file to its name. MOVEFILE_WRITE_THROUGH returns once
// the move is on disk: syncDir has nothing to do on windows.
func rename(from, to string) error {
	f, err := windows.UTF16PtrFromString(from)
	if err != nil {
		return err
	}
	t, err := windows.UTF16PtrFromString(to)
	if err != nil {
		return err
	}
	if err := windows.MoveFileEx(f, t, windows.MOVEFILE_REPLACE_EXISTING|windows.MOVEFILE_WRITE_THROUGH); err != nil {
		return &os.LinkError{Op: "rename", Old: from, New: to, Err: err}
	}
	return nil
}
