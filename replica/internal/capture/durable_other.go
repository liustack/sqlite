//go:build !windows

package capture

import "os"

// renameFS is rename.
func renameFS(from, to string) error { return os.Rename(from, to) }

// fsyncDir is syncDir: an fsync of the folder.
func fsyncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	err = d.Sync()
	if cerr := d.Close(); err == nil {
		err = cerr
	}
	return err
}
